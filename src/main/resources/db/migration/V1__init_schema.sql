CREATE TABLE app_users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_sub      VARCHAR(128) NOT NULL UNIQUE,
    email           VARCHAR(320) NOT NULL,
    display_name    VARCHAR(200) NOT NULL,
    avatar_url      VARCHAR(1000),
    created_at      TIMESTAMP NOT NULL
);

CREATE TABLE projects (
    id                      VARCHAR(64) PRIMARY KEY,
    name                    VARCHAR(200) NOT NULL,
    summary                 VARCHAR(500) NOT NULL,
    description             TEXT NOT NULL,
    original_platform       VARCHAR(100) NOT NULL,
    target_platforms_json   TEXT NOT NULL,
    category                VARCHAR(64) NOT NULL,
    status                  VARCHAR(32) NOT NULL,
    repo_url                VARCHAR(1000),
    homepage_url            VARCHAR(1000),
    image_url               VARCHAR(1000),
    screenshot_urls_json    TEXT NOT NULL,
    tags_json               TEXT NOT NULL,
    updated_at              DATE NOT NULL,
    featured                BOOLEAN NOT NULL DEFAULT FALSE,
    trending_until          DATE,
    publication_status      VARCHAR(32) NOT NULL,
    vote_count              INT NOT NULL DEFAULT 0,
    submitted_by_user_id    BIGINT,
    submitted_by_display_name VARCHAR(200),
    CONSTRAINT fk_projects_submitter FOREIGN KEY (submitted_by_user_id) REFERENCES app_users(id)
);

CREATE INDEX idx_projects_publication ON projects(publication_status);
CREATE INDEX idx_projects_category ON projects(category);
CREATE INDEX idx_projects_votes ON projects(vote_count DESC);

CREATE TABLE votes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    project_id  VARCHAR(64) NOT NULL,
    created_at  TIMESTAMP NOT NULL,
    CONSTRAINT uq_votes_user_project UNIQUE (user_id, project_id),
    CONSTRAINT fk_votes_user FOREIGN KEY (user_id) REFERENCES app_users(id),
    CONSTRAINT fk_votes_project FOREIGN KEY (project_id) REFERENCES projects(id)
);
